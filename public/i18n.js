export function translate(key, language = 'zh') {
  return (language === 'en' ? en : language === 'ja' ? ja : {})[key] || key;
}

export function applyStaticTranslations(language) {
  document.documentElement.lang = language === 'ja' ? 'ja' : language === 'en' ? 'en' : 'zh-CN';
  for (const element of document.querySelectorAll('[data-i18n]')) {
    element.textContent = translate(element.dataset.i18n, language);
  }
  for (const element of document.querySelectorAll('[data-i18n-placeholder]')) {
    element.placeholder = translate(element.dataset.i18nPlaceholder, language);
  }
  for (const element of document.querySelectorAll('[data-i18n-title]')) {
    element.title = translate(element.dataset.i18nTitle, language);
  }
}
